def main(dry_run=False):
    client = utils.client("asheis")
    to_be_published = client.products_by_query("tag:'26_oct_1' OR tag:'26_oct_2'")
    to_be_published_titles = [p["title"] for p in to_be_published]
    all_products = client.products_by_query()
    processing = [p for p in all_products if p["title"] not in to_be_published_titles]

    location_id = client.location_id_by_name(client.LOCATIONS[0])
    for p in processing:
        for v in p["variants"]["nodes"]:
            sku, stock = v["sku"], stocks[v["sku"]]
            print(
                f"{'would update' if dry_run else 'updating'} {sku} "
                f"{v['inventoryQuantity']} -> {stock}"
            )
            if not dry_run:
                client.set_inventory_quantity_by_sku_and_location_id(
                    sku, location_id, stock
                )


if __name__ == "__main__":
    main()
